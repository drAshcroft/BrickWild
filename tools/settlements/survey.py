def load_koppen(raw: Path) -> dict:
    z = zipfile.ZipFile(raw / "kg_ascii.zip")
    text = z.read(z.namelist()[0]).decode("ascii")
    grid = {}
    for line in text.splitlines()[1:]:
        parts = line.split()
        if len(parts) != 3:
            continue
        grid[(round(float(parts[0]) * 4), round(float(parts[1]) * 4))] = parts[2]
    return grid


def koppen_at(grid, lat, lon):
    """Nearest 0.5 deg cell; coastal points often fall in an ocean (missing)
    cell, so search outward a few cells."""
    ci = math.floor(lat * 2) / 2 + 0.25
    cj = math.floor(lon * 2) / 2 + 0.25
    for r in range(0, 4):
        best = None
        for di in range(-r, r + 1):
            for dj in range(-r, r + 1):
                if max(abs(di), abs(dj)) != r:
                    continue
                k = (round((ci + di * 0.5) * 4), round((cj + dj * 0.5) * 4))
                if k in grid:
                    d = di * di + dj * dj
                    if best is None or d < best[0]:
                        best = (d, grid[k])
        if best:
            return best[1]
    return "?"


def climate_axes(kg: str) -> tuple[float, float]:
    """Koppen letter -> (thermal, moisture), coarse but ordered, so climate
    can sit in the same distance space as altitude and relief."""
    if not kg or kg == "?":
        return (2.5, 2.0)
    g = kg[0]
    if g == "A":
        thermal = 4.0
    elif g == "C":
        thermal = 3.0
    elif g == "D":
        thermal = 1.8
    elif g == "E":
        thermal = 0.0 if kg.startswith("EF") else 0.7
    else:  # B
        thermal = 3.6 if kg.endswith("h") else 2.2
    if g == "B":
        moisture = 0.0 if kg[1] == "W" else 1.0
    elif g == "E":
        moisture = 2.0
    else:
        second = kg[1] if len(kg) > 1 else "f"
        moisture = {"f": 3.2, "m": 3.0, "w": 2.4, "s": 2.2}.get(second, 2.6)
    return (thermal, moisture)



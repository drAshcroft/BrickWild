"""World settlement survey: a COVERAGE sample of real towns and villages.

Not the mean village. A set chosen so that its members span the ways real
settlements differ -- climate, altitude, relief, water, isolation, size --
and then measured from OpenStreetMap and a DEM so the arrangement each one
actually has can be compared with what VillageSpec can generate.

Stages, each cached under the data directory and each re-runnable:

  pool      GeoNames cities500 -> populated places 500..25 000 people, each with
            Koppen class (Kottek 2006), coast / major river / lake distance and
            island area (Natural Earth 10 m)
  relief    stratified candidate subset -> DEM ring samples (OpenTopoData
            mapzen) -> local relief and slope
  select    farthest-point (maximin) order in rank-normalised environment space,
            with a per-country cap, plus the hand-picked unusual sites
  morph     Overpass (buildings, streets, water, walls, worship) + a DEM grid
            per site -> arrangement metrics
  report    tests/fixtures/settlements/world_settlements.json, contact sheets,
            environment->morphology correlations

Run with the user's venv (numpy, scipy, shapely, matplotlib, requests):

  C:/projects/.local/Scripts/python.exe -I tools/settlements/survey.py all \
      --data artifacts/settlements --repo .

See docs/SETTLEMENT_TESTSET.md.
"""

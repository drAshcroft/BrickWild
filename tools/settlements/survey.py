class OverpassUnavailable(RuntimeError):
    pass


def overpass(cache: Cache, query: str):
    """Cached Overpass call. The public server is often at capacity and asks
    for exponential backoff; after `tries` it raises OverpassUnavailable so
    the caller can skip ONE site and a later run can fill it from scratch."""
    hit = cache.get("overpass", query)
    if hit is not None:
        return hit
    wait = 10.0
    for attempt in range(12):
        url = OVERPASS[0] if attempt % 3 != 2 else OVERPASS[1]
        cache.throttle("overpass", 3.0)
        try:
            resp = requests.post(url, data={"data": query}, headers={"User-Agent": UA}, timeout=200)
            if resp.status_code == 200 and resp.text.lstrip().startswith("{"):
                js = resp.json()
                if "runtime error" not in js.get("remark", ""):
                    cache.put("overpass", query, js)
                    return js
                log(f"  overpass remark: {js['remark'][:120]}")
            else:
                log(f"  overpass {url.split('/')[2]} HTTP {resp.status_code}, wait {int(wait)} s")
        except requests.RequestException as e:
            log(f"  overpass {url.split('/')[2]}: {type(e).__name__}, wait {int(wait)} s")
        time.sleep(wait)
        wait = min(wait * 2.0, 300.0)
    raise OverpassUnavailable("overpass unavailable")



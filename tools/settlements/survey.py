class Cache:
    """Every network answer on disk, keyed by the request, so a re-run is free
    and a published fixture can be regenerated byte for byte."""

    def __init__(self, root: Path):
        self.root = root / "cache"
        self.root.mkdir(parents=True, exist_ok=True)
        self.last: dict[str, float] = {}

    def _path(self, kind: str, key: str) -> Path:
        h = hashlib.sha1(key.encode("utf-8")).hexdigest()[:20]
        d = self.root / kind
        d.mkdir(exist_ok=True)
        return d / f"{h}.json"

    def get(self, kind, key):
        p = self._path(kind, key)
        if p.exists():
            return json.loads(p.read_text(encoding="utf-8"))
        return None

    def put(self, kind, key, value):
        self._path(kind, key).write_text(json.dumps(value), encoding="utf-8")

    def throttle(self, kind, gap):
        t = self.last.get(kind, 0.0)
        wait = t + gap - time.time()
        if wait > 0:
            time.sleep(wait)
        self.last[kind] = time.time()


def haversine_km(lat1, lon1, lat2, lon2):
    lat1, lon1, lat2, lon2 = map(np.radians, (lat1, lon1, lat2, lon2))
    a = np.sin((lat2 - lat1) / 2) ** 2 + np.cos(lat1) * np.cos(lat2) * np.sin((lon2 - lon1) / 2) ** 2
    return 6371.0 * 2 * np.arcsin(np.sqrt(np.clip(a, 0, 1)))


class Local:
    """Equirectangular metres about a centre; plenty for a 1.4 km disc."""

    def __init__(self, lat0, lon0):
        self.lat0, self.lon0 = lat0, lon0
        self.kx = math.cos(math.radians(lat0)) * 111320.0
        self.ky = 110540.0

    def xy(self, lat, lon):
        return ((lon - self.lon0) * self.kx, (lat - self.lat0) * self.ky)

    def ll(self, x, y):
        return (self.lat0 + y / self.ky, self.lon0 + x / self.kx)



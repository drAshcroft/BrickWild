def stage_pool(data: Path):
    raw = data / "raw"
    log("pool: reading GeoNames cities500")
    z = zipfile.ZipFile(raw / "cities500.zip")
    rows = []
    with z.open("cities500.txt") as fh:
        for line in io.TextIOWrapper(fh, encoding="utf-8"):
            f = line.rstrip("\n").split("\t")
            if len(f) < 19 or f[6] != "P" or f[7] not in KEEP_CODES:
                continue
            pop = int(f[14] or 0)
            if pop < POP_MIN or pop > POP_MAX:
                continue
            dem = f[16]
            rows.append({"geonameid": int(f[0]), "name": f[1], "lat": float(f[4]), "lon": float(f[5]),
                         "code": f[7], "cc": f[8], "pop": pop,
                         "dem": int(dem) if dem and dem.lstrip("-").isdigit() and int(dem) > -9000 else 0})
    log(f"pool: {len(rows)} places in [{POP_MIN}, {POP_MAX}] people")
    lat = np.array([r["lat"] for r in rows])
    lon = np.array([r["lon"] for r in rows])
    pts = shapely.points(lon, lat)

    def nearest_km(path: Path, label: str, polygons=False):
        gj = json.loads(path.read_text(encoding="utf-8"))
        geoms = []
        for feat in gj["features"]:
            g = shape(feat["geometry"])
            if polygons:
                g = g.boundary
            geoms.append(g)
        tree = STRtree(geoms)
        idx = tree.nearest(pts)
        lines = shapely.shortest_line(pts, np.array(geoms, dtype=object)[idx])
        coords = shapely.get_coordinates(lines).reshape(-1, 2, 2)
        km = haversine_km(coords[:, 0, 1], coords[:, 0, 0], coords[:, 1, 1], coords[:, 1, 0])
        log(f"pool: {label} distance done")
        return km

    coast = nearest_km(raw / "ne_10m_coastline.geojson", "coast")
    river = nearest_km(raw / "ne_10m_rivers_lake_centerlines.geojson", "river")
    lake = nearest_km(raw / "ne_10m_lakes.geojson", "lake", polygons=True)

    land = json.loads((raw / "ne_10m_land.geojson").read_text(encoding="utf-8"))
    polys = []
    for feat in land["features"]:
        g = shape(feat["geometry"])
        polys.extend(list(g.geoms) if isinstance(g, MultiPolygon) else [g])
    areas = np.array([p.area * 111.32 * 110.54 * math.cos(math.radians(p.centroid.y)) for p in polys])
    tree = STRtree(polys)
    pi, gi = tree.query(pts, predicate="intersects")
    land_km2 = np.full(len(rows), np.nan)
    land_km2[pi] = areas[gi]
    # a point the 10 m land polygons miss is on an islet they do not draw
    land_km2[np.isnan(land_km2)] = 1.0
    log("pool: island areas done")

    kg = load_koppen(raw)
    out = data / "pool.csv"
    with out.open("w", newline="", encoding="utf-8") as fh:
        w = csv.writer(fh)
        w.writerow(["geonameid", "name", "lat", "lon", "code", "cc", "pop", "dem", "koppen",
                    "coast_km", "river_km", "lake_km", "landmass_km2"])
        for i, r in enumerate(rows):
            w.writerow([r["geonameid"], r["name"], r["lat"], r["lon"], r["code"], r["cc"], r["pop"],
                        r["dem"], koppen_at(kg, r["lat"], r["lon"]),
                        round(float(coast[i]), 2), round(float(river[i]), 2), round(float(lake[i]), 2),
                        round(float(land_km2[i]), 1)])
    log(f"pool: wrote {out}")


def read_pool(data: Path) -> list[dict]:
    rows = []
    with (data / "pool.csv").open(encoding="utf-8") as fh:
        for r in csv.DictReader(fh):
            for k in ("lat", "lon", "coast_km", "river_km", "lake_km", "landmass_km2"):
                r[k] = float(r[k])
            for k in ("geonameid", "pop", "dem"):
                r[k] = int(r[k])
            rows.append(r)
    return rows


# ------------------------------------------------------------ stage: relief

def water_class(r) -> str:
    if r["coast_km"] < 2.0:
        return "coast"
    if r["lake_km"] < 2.0:
        return "lake"
    if r["river_km"] < 3.0:
        return "river"
    return "inland"


def elev_band(e) -> int:
    return 0 if e < 200 else 1 if e < 800 else 2 if e < 1800 else 3 if e < 3000 else 4


def island_class(a) -> int:
    return 0 if a > 200000 else 1 if a > 2000 else 2


def stratified_candidates(pool, per_stratum, seed=7):
    """Up to `per_stratum` places from every (climate group, water, altitude band,
    island class) stratum, spread over countries. Rare strata are kept whole;
    the commonest (temperate lowland inland Europe) is cut hard."""
    rng = np.random.default_rng(seed)
    strata: dict[tuple, list] = {}
    for r in pool:
        key = (r["koppen"][:1], water_class(r), elev_band(r["dem"]), island_class(r["landmass_km2"]))
        strata.setdefault(key, []).append(r)
    out = []
    for key, members in sorted(strata.items()):
        rng.shuffle(members)
        by_cc: dict[str, list] = {}
        for m in members:
            by_cc.setdefault(m["cc"], []).append(m)
        # round-robin over countries so one well-mapped country cannot fill a stratum
        picked = []
        queues = list(by_cc.values())
        rng.shuffle(queues)
        while len(picked) < per_stratum and any(queues):
            for q in queues:
                if q and len(picked) < per_stratum:
                    picked.append(q.pop())
        out.extend(picked)
    return out, strata


def fetch_elevations(cache: Cache, lats, lons, dataset: str = "mapzen") -> list[float]:
    """OpenTopoData `mapzen` (a global SRTM/ETOPO/GMTED composite, ~30-90 m),
    100 points per call, 1 call per second, cached per call. Open-Meteo's
    elevation API counts every POINT against its quota, which allows about a
    hundred 100-point calls a day -- far too few for a DEM grid per site.
    `dataset` picks another OpenTopoData set (srtm30m, aster30m); its answers
    are cached under their own kind so a 30 m grid never reuses 90 m ones."""
    url = ELEVATION if dataset == "mapzen" else ELEVATION.rsplit("/", 1)[0] + "/" + dataset
    kind = "elev_otd" if dataset == "mapzen" else "elev_otd_" + dataset
    out = []
    for s in range(0, len(lats), 100):
        locs = "|".join(f"{a:.5f},{b:.5f}" for a, b in zip(lats[s:s + 100], lons[s:s + 100]))
        hit = cache.get(kind, locs)
        if hit is None:
            for attempt in range(8):
                cache.throttle("elev", 1.15)
                try:
                    resp = requests.post(url, json={"locations": locs}, headers={"User-Agent": UA}, timeout=90)
                except requests.RequestException as e:
                    log(f"  elevation: {e}")
                    time.sleep(10)
                    continue
                if resp.status_code == 200 and resp.json().get("status") == "OK":
                    hit = [r["elevation"] for r in resp.json()["results"]]
                    cache.put(kind, locs, hit)
                    break
                log(f"  elevation HTTP {resp.status_code}, retry {attempt}")
                time.sleep(10 * (attempt + 1))
            if hit is None:
                raise RuntimeError("elevation service unavailable")
        out.extend(float(v) if v is not None else float("nan") for v in hit)
    return out


def sea_clip(z, coastal: bool):
    """Mapzen carries bathymetry: the sea floor off an atoll is "relief". Deep
    negatives are sea, so sea level; a coastal site's shallow negatives are
    sea too. Inland, a shallow negative is real ground (a polder, Siwa)."""
    z = np.asarray(z, dtype=float)
    z = np.where(z < -30.0, 0.0, z)
    return np.where(z < 0.0, 0.0, z) if coastal else z


RING = [(0.0, 0.0)] + [(rad, ang) for rad in (300.0, 800.0) for ang in range(0, 360, 45)]


def stage_relief(data: Path, per_stratum: int):
    cache = Cache(data)
    pool = read_pool(data)
    cands, strata = stratified_candidates(pool, per_stratum)
    log(f"relief: {len(strata)} strata, {len(cands)} candidates")
    lats, lons = [], []
    for r in cands:
        loc = Local(r["lat"], r["lon"])
        for rad, ang in RING:
            a = math.radians(ang)
            la, lo = loc.ll(rad * math.cos(a), rad * math.sin(a))
            lats.append(la)
            lons.append(lo)
    elev = fetch_elevations(cache, lats, lons)
    n = len(RING)
    out = []
    for i, r in enumerate(cands):
        e = sea_clip(elev[i * n:(i + 1) * n], r["coast_km"] < 3.0)
        c = e[0]
        inner, outer = e[1:9], e[9:17]
        r = dict(r)
        r["elev"] = round(float(c), 1)
        r["relief_800"] = round(float(np.nanmax(e) - np.nanmin(e)), 1)
        # mean absolute slope over the inner ring, percent
        r["slope_300"] = round(float(np.nanmean(np.abs(inner - c)) / 300.0 * 100.0), 2)
        # positive: the centre sits above its surroundings (hilltop / spur);
        # negative: in a hollow (valley floor, basin)
        r["prominence"] = round(float(c - np.nanmean(outer)), 1)
        out.append(r)
    (data / "candidates.json").write_text(json.dumps(out, indent=0), encoding="utf-8")
    log(f"relief: wrote {len(out)} candidates")



def env_vector(r) -> list[float]:
    t, m = climate_axes(r["koppen"])
    return [t, m, abs(r["lat"]),
            math.log10(max(r["elev"], 0.0) + 30.0),
            math.log10(r["relief_800"] + 5.0),
            math.log10(r["slope_300"] + 0.5),
            r["prominence"],
            math.log10(r["coast_km"] + 0.3),
            math.log10(r["river_km"] + 0.3),
            math.log10(r["lake_km"] + 0.3),
            math.log10(r["landmass_km2"] + 1.0),
            math.log10(r["pop"])]



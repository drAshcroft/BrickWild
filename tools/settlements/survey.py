def ring_polys(el, loc: Local):
    """Polygons of a way or (outer members of) a relation, in local metres."""
    out = []
    if el["type"] == "way" and "geometry" in el:
        pts = [loc.xy(p["lat"], p["lon"]) for p in el["geometry"]]
        if len(pts) >= 4 and pts[0] == pts[-1]:
            p = Polygon(pts)
            if not p.is_valid:
                p = p.buffer(0)
            if not p.is_empty:
                out.append(p)
    elif el["type"] == "relation":
        # an outer ring is often drawn as several ways (a lagoon, a river's
        # banks): join the pieces before making rings, or the water is lost
        # and the inner rings are islands: cut them out, or an island village
        # in a lake reads as built on the water
        from shapely.ops import linemerge, polygonize
        rings = {"outer": [], "inner": []}
        for m in el.get("members", []):
            role = m.get("role") or "outer"
            if role in rings and "geometry" in m:
                pts = [loc.xy(p["lat"], p["lon"]) for p in m["geometry"] if p]
                if len(pts) >= 2:
                    rings[role].append(LineString(pts))
        if rings["outer"]:
            holes = shapely.union_all(list(polygonize(linemerge(rings["inner"])))) if rings["inner"] else None
            for p in polygonize(linemerge(rings["outer"])):
                p = p.buffer(0)
                if holes is not None and not holes.is_empty:
                    p = p.difference(holes)
                if not p.is_empty:
                    out.append(p)
    return [q for p in out for q in (p.geoms if isinstance(p, MultiPolygon) else [p])]


def way_line(el, loc: Local):
    if "geometry" not in el:
        return None
    pts = [loc.xy(p["lat"], p["lon"]) for p in el["geometry"] if p]
    return LineString(pts) if len(pts) >= 2 else None



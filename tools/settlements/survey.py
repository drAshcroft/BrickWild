def parse_site(js, loc: Local):
    b, roads, paths, water_poly, water_line, coast, walls, worship, squares, piers = ([] for _ in range(10))
    for el in js.get("elements", []):
        t = el.get("tags", {})
        if t.get("amenity") == "place_of_worship":
            if el["type"] == "node":
                worship.append(Point(loc.xy(el["lat"], el["lon"])))
            else:
                ps = ring_polys(el, loc)
                if ps:
                    worship.append(ps[0].centroid)
        if "building" in t and t["building"] not in ("no", "roof", "ruins") and el["type"] != "node":
            b.extend(ring_polys(el, loc))
        elif "highway" in t and el["type"] == "way":
            hw = t["highway"]
            if hw in SKIP_HIGHWAY or t.get("area") == "yes":
                if t.get("area") == "yes" and hw == "pedestrian":
                    squares.extend(ring_polys(el, loc))
                continue
            ln = way_line(el, loc)
            if ln is None:
                continue
            item = {"line": ln, "nodes": el.get("nodes", []), "hw": hw,
                    "bridge": t.get("bridge") not in (None, "no"), "tunnel": t.get("tunnel") not in (None, "no"),
                    "steps": hw == "steps"}
            (paths if hw in MINOR_PATH else roads).append(item)
        elif t.get("natural") == "coastline":
            ln = way_line(el, loc)
            if ln is not None:
                coast.append(ln)
        elif t.get("natural") == "water":
            water_poly.extend(ring_polys(el, loc))
        elif "waterway" in t and el["type"] == "way":
            ln = way_line(el, loc)
            if ln is not None:
                water_line.append((ln, t["waterway"]))
        elif t.get("barrier") == "city_wall" or t.get("historic") == "citywalls":
            ln = way_line(el, loc)
            if ln is not None:
                walls.append(ln)
        elif t.get("place") == "square" or t.get("landuse") == "village_green" or t.get("leisure") == "common":
            squares.extend(ring_polys(el, loc))
        elif t.get("man_made") == "pier":
            ln = way_line(el, loc)
            if ln is not None:
                piers.append(ln)
    b = [p for p in b if p.area >= 6.0]
    return {"buildings": b, "roads": roads, "paths": paths, "water_poly": water_poly,
            "water_line": water_line, "coast": coast, "walls": walls, "worship": worship,
            "squares": squares, "piers": piers}


class Dem:
    def __init__(self, xs, ys, z):
        self.xs, self.ys, self.z = xs, ys, z
        self.step = xs[1] - xs[0]
        gy, gx = np.gradient(z, self.step)
        self.gx, self.gy = gx, gy

    def _bil(self, field, x, y):
        fx = np.clip((np.asarray(x) - self.xs[0]) / self.step, 0, len(self.xs) - 1.001)
        fy = np.clip((np.asarray(y) - self.ys[0]) / self.step, 0, len(self.ys) - 1.001)
        i0, j0 = fy.astype(int), fx.astype(int)
        ty, tx = fy - i0, fx - j0
        return (field[i0, j0] * (1 - tx) * (1 - ty) + field[i0, j0 + 1] * tx * (1 - ty)
                + field[i0 + 1, j0] * (1 - tx) * ty + field[i0 + 1, j0 + 1] * tx * ty)

    def height(self, x, y):
        return self._bil(self.z, x, y)

    def grad(self, x, y):
        return self._bil(self.gx, x, y), self._bil(self.gy, x, y)


def site_dem(cache: Cache, lat, lon, coastal=True, dataset="mapzen", step=DEM_STEP_M, half=None) -> Dem:
    loc = Local(lat, lon)
    half = RADIUS_M + step if half is None else half
    xs = np.arange(-half, half + 0.1, step)
    ys = xs.copy()
    lats, lons = [], []
    for y in ys:
        for x in xs:
            la, lo = loc.ll(x, y)
            lats.append(la)
            lons.append(lo)
    z = np.array(fetch_elevations(cache, lats, lons, dataset)).reshape(len(ys), len(xs))
    if np.isnan(z).any():
        z = np.where(np.isnan(z), np.nanmean(z), z)
    return Dem(xs, ys, sea_clip(z, coastal))


def angle_mod(a, period):
    a = np.mod(a, period)
    return np.minimum(a, period - a)


def bearing(dx, dy):
    return np.degrees(np.arctan2(dx, dy))  # compass-like, 0 = north


def orientation_order(bearings, weights):
    """Boeing's street-orientation order: 1 a perfect grid, 0 uniform. 36
    bins over 0..180, both directions folded."""
    if len(bearings) == 0 or np.sum(weights) <= 0:
        return float("nan")
    hist, _ = np.histogram(np.mod(bearings, 180.0), bins=36, range=(0, 180), weights=weights)
    p = hist / hist.sum()
    p = p[p > 0]
    h = -np.sum(p * np.log(p))
    hmax, hg = math.log(36), math.log(4)
    # Boeing folds bearings over 360 deg / 36 bins; the grid limit there is 4 bins.
    # Over 180 deg the grid is 2 bins.
    hg = math.log(2)
    return float(1.0 - ((h - hg) / (hmax - hg)) ** 2) if h > hg else 1.0


def clusters(cent: np.ndarray, link: float):
    from scipy.sparse.csgraph import connected_components
    from scipy.spatial import cKDTree
    from scipy.sparse import coo_matrix
    tree = cKDTree(cent)
    pairs = tree.query_pairs(link, output_type="ndarray")
    n = len(cent)
    m = coo_matrix((np.ones(len(pairs)), (pairs[:, 0], pairs[:, 1])), shape=(n, n)) if len(pairs) else coo_matrix((n, n))
    k, lab = connected_components(m, directed=False)
    return k, lab


def measure(site, dem: Dem, geo: dict):
    from scipy.spatial import cKDTree
    B = geo["buildings"]
    disc = Point(0, 0).buffer(RADIUS_M, 64)
    B = [p for p in B if disc.contains(p.centroid)]
    m: dict = {"osm_buildings": len(B)}
    if len(B) < MIN_BUILDINGS:
        m["usable"] = False
        return m, None
    m["usable"] = True
    cent = np.array([[p.centroid.x, p.centroid.y] for p in B])
    area = np.array([p.area for p in B])
    k, lab = clusters(cent, CLUSTER_LINK_M)
    sizes = np.bincount(lab)
    # the settlement body: the cluster with most BUILDINGS, those within 250 m
    # of the named point counting triple. By count, not footprint: one huge
    # mapped block (a roofed old town, a warehouse) must not outweigh a village
    near = np.linalg.norm(cent, axis=1) < 250
    score = np.bincount(lab, weights=(1.0 + 2.0 * near))
    main = int(score.argmax())
    sel = lab == main
    mc, ma = cent[sel], area[sel]
    mb = [B[i] for i in np.where(sel)[0]]
    m["body_buildings"] = int(sel.sum())
    m["body_share"] = round(float(sel.sum() / len(B)), 3)
    m["clusters_ge5"] = int((sizes >= 5).sum())
    m["footprint_median_m2"] = round(float(np.median(ma)), 1)
    m["footprint_p90_m2"] = round(float(np.percentile(ma, 90)), 1)
    m["footprint_cv"] = round(float(np.std(ma) / np.mean(ma)), 3)
    hull = shapely.MultiPoint(mc).convex_hull
    hull_a = max(hull.area, 1.0)
    m["body_hull_ha"] = round(hull_a / 1e4, 2)
    m["coverage"] = round(float(ma.sum() / hull_a), 3)
    m["compactness"] = round(float(4 * math.pi * hull_a / max(hull.length, 1.0) ** 2), 3)
    # Clark-Evans nearest-neighbour ratio over the body's hull: < 1 clumped,
    # ~1 random, > 1 regular / spaced
    if len(mc) >= 3:
        d, _ = cKDTree(mc).query(mc, k=2)
        m["clark_evans"] = round(float(d[:, 1].mean() / (0.5 / math.sqrt(len(mc) / hull_a))), 3)
        m["nn_median_m"] = round(float(np.median(d[:, 1])), 1)
    if len(mc) >= 3:
        cov = np.cov((mc - mc.mean(axis=0)).T)
        ev = np.sort(np.linalg.eigvalsh(cov))
        m["elongation"] = round(float(math.sqrt(ev[1] / max(ev[0], 1e-6))), 2)
    m["body_offset_m"] = round(float(np.linalg.norm(mc.mean(axis=0))), 1)

    # --- streets
    body_zone = hull.buffer(40)
    seg_b, seg_w, seg_mid = [], [], []
    deg: dict[int, int] = {}
    road_len = 0.0
    for r in geo["roads"]:
        c = np.asarray(r["line"].coords)
        nds = r["nodes"]
        for i, nd in enumerate(nds):
            if i == 0 or i == len(nds) - 1:
                deg[nd] = deg.get(nd, 0) + 1
            else:
                deg[nd] = deg.get(nd, 0) + 2
        dxy = np.diff(c, axis=0)
        L = np.hypot(dxy[:, 0], dxy[:, 1])
        mid = (c[:-1] + c[1:]) / 2
        inside = shapely.contains_xy(body_zone, mid[:, 0], mid[:, 1])
        seg_b.append(bearing(dxy[inside, 0], dxy[inside, 1]))
        seg_w.append(L[inside])
        seg_mid.append(mid[inside])
        road_len += float(L[inside].sum())
    seg_b = np.concatenate(seg_b) if seg_b else np.zeros(0)
    seg_w = np.concatenate(seg_w) if seg_w else np.zeros(0)
    seg_mid = np.concatenate(seg_mid) if seg_mid else np.zeros((0, 2))
    m["road_km_per_ha"] = round(road_len / 1000.0 / max(hull_a / 1e4, 0.01), 3)
    m["orientation_order"] = round(orientation_order(seg_b, seg_w), 3) if len(seg_b) else None
    ends = sum(1 for v in deg.values() if v == 1)
    inter = sum(1 for v in deg.values() if v >= 3)
    m["dead_end_ratio"] = round(ends / max(ends + inter, 1), 3)
    m["intersections_per_ha"] = round(inter / max(hull_a / 1e4, 0.01), 3)
    m["steps_ways"] = sum(1 for r in geo["paths"] if r["steps"])
    m["bridges"] = sum(1 for r in geo["roads"] + geo["paths"] if r["bridge"])
    m["tunnels"] = sum(1 for r in geo["roads"] if r["tunnel"])

    # --- frontage: is a house turned toward its street?
    all_lines = [r["line"] for r in geo["roads"]] + [r["line"] for r in geo["paths"]]
    align, setback = [], []
    if all_lines:
        tree = STRtree(all_lines)
        for p in mb:
            mrr = p.minimum_rotated_rectangle
            cc = np.asarray(mrr.exterior.coords)[:4]
            e1, e2 = cc[1] - cc[0], cc[2] - cc[1]
            ax = e1 if np.hypot(*e1) >= np.hypot(*e2) else e2
            j = tree.nearest(p.centroid)
            ln = all_lines[j]
            dist = ln.distance(p)
            if dist > 40:
                continue
            s = ln.project(p.centroid)
            a0, a1 = ln.interpolate(max(s - 3, 0)), ln.interpolate(min(s + 3, ln.length))
            rb = bearing(a1.x - a0.x, a1.y - a0.y)
            hb = bearing(ax[0], ax[1])
            align.append(float(angle_mod(hb - rb, 90.0)))
            setback.append(dist)
    if align:
        al = np.array(align)
        m["frontage_aligned"] = round(float((al < 15).mean()), 3)   # random: 1/3
        m["setback_median_m"] = round(float(np.median(setback)), 1)
        m["road_reached"] = round(len(align) / len(mb), 3)

    # --- terrain under the body
    hz = dem.height(mc[:, 0], mc[:, 1])
    gx, gy = dem.grad(mc[:, 0], mc[:, 1])
    slope = np.hypot(gx, gy) * 100
    m["elev_body_m"] = round(float(np.median(hz)), 1)
    m["elev_span_m"] = round(float(np.percentile(hz, 95) - np.percentile(hz, 5)), 1)
    m["slope_median_pct"] = round(float(np.median(slope)), 2)
    m["slope_p90_pct"] = round(float(np.percentile(slope, 90)), 2)
    m["relief_disc_m"] = round(float(dem.z.max() - dem.z.min()), 1)
    # where the body sits in the disc's elevation: 0 the lowest ground, 1 the top
    zr = np.sort(dem.z.ravel())
    m["body_elev_pctile"] = round(float(np.searchsorted(zr, np.median(hz)) / len(zr)), 3)
    # contour following: on ground steeper than 8 %, the share of street length
    # within 30 deg of the contour (random would be 1/3)
    if len(seg_mid):
        sgx, sgy = dem.grad(seg_mid[:, 0], seg_mid[:, 1])
        ss = np.hypot(sgx, sgy)
        steep = ss > 0.08
        if seg_w[steep].sum() > 100:
            contour_b = bearing(-sgy[steep], sgx[steep])
            d = angle_mod(seg_b[steep] - contour_b, 180.0)
            m["street_contour_share"] = round(float(seg_w[steep][d < 30].sum() / seg_w[steep].sum()), 3)
            m["street_steep_share"] = round(float(seg_w[steep].sum() / max(seg_w.sum(), 1)), 3)
    bsteep = slope > 8
    if bsteep.sum() >= 10:
        axes = []
        for i in np.where(bsteep)[0]:
            cc = np.asarray(mb[i].minimum_rotated_rectangle.exterior.coords)[:4]
            e1, e2 = cc[1] - cc[0], cc[2] - cc[1]
            ax = e1 if np.hypot(*e1) >= np.hypot(*e2) else e2
            axes.append(bearing(ax[0], ax[1]))
        cb = bearing(-gy[bsteep], gx[bsteep])
        m["house_contour_share"] = round(float((angle_mod(np.array(axes) - cb, 180.0) < 30).mean()), 3)

    # --- water
    water = [p for p in geo["water_poly"]]
    wl = [ln for ln, _ in geo["water_line"]] + geo["coast"]
    wgeoms = water + wl
    if wgeoms:
        wt = STRtree(wgeoms)
        pts = shapely.points(mc)
        idx = wt.nearest(pts)
        dist = shapely.distance(pts, np.array(wgeoms, dtype=object)[idx])
        m["water_within_30m"] = round(float((dist < 30).mean()), 3)
        m["water_median_m"] = round(float(np.median(dist)), 1)
    else:
        m["water_within_30m"] = 0.0
    if water:
        wu = shapely.union_all(water)
        # the biggest standing water the body touches: a pond, a lagoon, a lake
        near_body = hull.buffer(60)
        m["adjacent_water_ha"] = round(max((w.area for w in water if w.intersects(near_body)), default=0.0) / 1e4, 2)
        over = [p for p in mb if p.intersection(wu).area > 0.5 * p.area]
        m["over_water_share"] = round(len(over) / len(mb), 3)
    else:
        m["over_water_share"] = 0.0
    m["coast_in_disc"] = bool(geo["coast"])
    m["waterway_kinds"] = sorted({k for _, k in geo["water_line"]})
    m["piers"] = len(geo["piers"])

    # --- landmarks and edges
    m["city_wall"] = bool(geo["walls"])
    m["squares"] = sum(1 for s in geo["squares"] if body_zone.intersects(s))
    w_in = [p for p in geo["worship"] if body_zone.contains(p)]
    m["worship"] = len(w_in)
    if w_in:
        wz = [float(dem.height(p.x, p.y)) for p in w_in]
        hs = np.sort(hz)
        m["worship_elev_pctile"] = round(float(np.searchsorted(hs, max(wz)) / len(hs)), 3)
        c0 = mc.mean(axis=0)
        rg = math.sqrt(hull_a / math.pi)
        m["worship_centrality"] = round(float(min(np.hypot(p.x - c0[0], p.y - c0[1]) for p in w_in) / rg), 3)
    return m, {"main": sel, "cent": cent, "lab": lab}


def resolve_curated(cache: Cache, row) -> dict | None:
    key = f"{row['name']}|{row['cc']}"
    hit = cache.get("nominatim", key)
    if hit is None:
        cache.throttle("nominatim", 1.2)
        resp = requests.get(NOMINATIM, params={"q": row["name"], "countrycodes": row["cc"], "format": "jsonv2",
                                               "limit": 8, "addressdetails": 0},
                            headers={"User-Agent": UA}, timeout=60)
        hit = resp.json() if resp.status_code == 200 else []
        cache.put("nominatim", key, hit)
    best = None
    for h in hit:
        la, lo = float(h["lat"]), float(h["lon"])
        d = float(haversine_km(la, lo, row["near"][0], row["near"][1]))
        if d > 25:
            continue
        rank = (0 if h.get("category") == "place" or h.get("class") == "place" else 1, d)
        if best is None or rank < best[0]:
            best = (rank, la, lo, h.get("display_name", ""))
    if best is None:
        return None
    return {"lat": best[1], "lon": best[2], "osm_name": best[3]}


def environment_for(cache: Cache, data: Path, lat, lon, pool_kg=None):
    """Recompute the cheap environment fields for an arbitrary point (the
    curated sites are not in the pool)."""
    raw = data / "raw"
    if not hasattr(environment_for, "_ctx"):
        ctx = {"kg": load_koppen(raw)}
        for name, poly in (("coast", False), ("river", False), ("lake", True)):
            f = {"coast": "ne_10m_coastline", "river": "ne_10m_rivers_lake_centerlines", "lake": "ne_10m_lakes"}[name]
            gj = json.loads((raw / f"{f}.geojson").read_text(encoding="utf-8"))
            geoms = [shape(ft["geometry"]).boundary if poly else shape(ft["geometry"]) for ft in gj["features"]]
            ctx[name] = (STRtree(geoms), geoms)
        land = json.loads((raw / "ne_10m_land.geojson").read_text(encoding="utf-8"))
        polys = []
        for ft in land["features"]:
            g = shape(ft["geometry"])
            polys.extend(list(g.geoms) if isinstance(g, MultiPolygon) else [g])
        ctx["land"] = (STRtree(polys), polys)
        environment_for._ctx = ctx
    ctx = environment_for._ctx
    p = Point(lon, lat)
    out = {"koppen": koppen_at(ctx["kg"], lat, lon)}
    for name in ("coast", "river", "lake"):
        tree, geoms = ctx[name]
        g = geoms[tree.nearest(p)]
        a, b = shapely.get_coordinates(shapely.shortest_line(p, g))
        out[f"{name}_km"] = round(float(haversine_km(a[1], a[0], b[1], b[0])), 2)
    tree, polys = ctx["land"]
    hits = tree.query(p, predicate="intersects")
    if len(hits):
        g = polys[hits[0]]
        out["landmass_km2"] = round(g.area * 111.32 * 110.54 * math.cos(math.radians(g.centroid.y)), 1)
    else:
        out["landmass_km2"] = 1.0
    return out


def stage_morph(data: Path, sample_n: int, curated_only=False):
    """`curated_only` measures just the hand-picked list, into its own file: a
    second process can fill the shared cache while the first walks the sample
    (Overpass grants each address two slots)."""
    cache = Cache(data)
    order = [] if curated_only else json.loads((data / "sample_order.json").read_text(encoding="utf-8"))
    sites = []
    # environment-sampled sites, walked in maximin order until enough are usable
    per_cc: dict[str, int] = {}
    tried = 0
    for c in order:
        if sum(1 for s in sites if s["source"] == "sampled") >= sample_n:
            break
        if per_cc.get(c["cc"], 0) >= COUNTRY_CAP:
            continue
        tried += 1
        s = {"id": f"gn{c['geonameid']}", "source": "sampled", "name": c["name"], "cc": c["cc"],
             "lat": c["lat"], "lon": c["lon"], "population": c["pop"], "maximin_rank": c["maximin_rank"],
             "env": {k: c[k] for k in ("koppen", "coast_km", "river_km", "lake_km", "landmass_km2")}}
        try:
            ok = morph_one(cache, s)
        except OverpassUnavailable:
            log(f"morph: sampled {c['name']} skipped, Overpass unavailable; re-run to fill it")
            continue
        log(f"morph [{len(sites)}] sampled #{c['maximin_rank']} {c['name']} ({c['cc']}): "
            f"{s['morph'].get('osm_buildings')} buildings{'' if ok else ' -- too thin, skipped'}")
        if ok:
            per_cc[c["cc"]] = per_cc.get(c["cc"], 0) + 1
            sites.append(s)
    log(f"morph: {tried} sampled candidates tried for {sample_n} usable")
    cur = json.loads(Path(__file__).with_name("curated_sites.json").read_text(encoding="utf-8"))["sites"]
    for row in cur:
        where = resolve_curated(cache, row)
        if where is None:
            log(f"morph: curated {row['name']} not resolved, skipped")
            continue
        s = {"id": "cu_" + row["name"].lower().replace(" ", "_").replace("'", ""), "source": "curated",
             "name": row["name"], "cc": row["cc"].upper(), "lat": where["lat"], "lon": where["lon"],
             "population": None, "phenomenon": row["phenomenon"], "why": row["why"],
             "env": environment_for(cache, data, where["lat"], where["lon"])}
        try:
            ok = morph_one(cache, s)
        except OverpassUnavailable:
            log(f"morph: curated {row['name']} skipped, Overpass unavailable; re-run to fill it")
            continue
        log(f"morph [{len(sites)}] curated {row['name']}: {s['morph'].get('osm_buildings')} buildings"
            f"{'' if ok else ' -- thin OSM, kept and flagged'}")
        sites.append(s)
    out = "sites_curated.json" if curated_only else "sites.json"
    (data / out).write_text(json.dumps(sites, indent=1), encoding="utf-8")
    log(f"morph: wrote {len(sites)} sites")


def morph_one(cache: Cache, s) -> bool:
    loc = Local(s["lat"], s["lon"])
    js = overpass(cache, site_query(s["lat"], s["lon"], RADIUS_M))
    geo = parse_site(js, loc)
    disc = Point(0, 0).buffer(RADIUS_M, 64)
    n = sum(1 for p in geo["buildings"] if disc.contains(p.centroid))
    if n < MIN_BUILDINGS:
        # too thin to measure: spend no elevation quota on it
        s["morph"] = {"osm_buildings": n, "usable": False}
        return False
    dem = site_dem(cache, s["lat"], s["lon"], s["env"].get("coast_km", 99) < 3.0)
    m, _ = measure(s, dem, geo)
    s["morph"] = m
    s["env"]["elev_m"] = round(float(dem.height(0.0, 0.0)), 1)
    s["env"]["relief_disc_m"] = round(float(dem.z.max() - dem.z.min()), 1)
    return bool(m.get("usable"))



def rank_normalise(X: np.ndarray) -> np.ndarray:
    """Each column -> its rank in [0, 1]. A heavy tail (one place at 5 000 m)
    must not swamp every other axis, and ties stay ties."""
    out = np.zeros_like(X, dtype=float)
    for j in range(X.shape[1]):
        col = X[:, j]
        order = col.argsort(kind="stable")
        ranks = np.empty(len(col))
        ranks[order] = np.arange(len(col))
        # average ties
        vals, inv = np.unique(col, return_inverse=True)
        sums = np.bincount(inv, weights=ranks)
        cnts = np.bincount(inv)
        out[:, j] = (sums / cnts)[inv] / max(len(col) - 1, 1)
    # climate gets double weight: thermal and moisture are each one coarse axis
    out[:, 0] *= 1.4
    out[:, 1] *= 1.4
    return out


def maximin_order(Z: np.ndarray, start: int) -> list[int]:
    """Farthest-point order: each next site is the one farthest from every site
    already chosen. The first k of the order cover the space as evenly as k
    points can; this is the opposite of sampling the mean."""
    n = len(Z)
    chosen = [start]
    d = np.linalg.norm(Z - Z[start], axis=1)
    for _ in range(n - 1):
        i = int(d.argmax())
        if d[i] <= 0:
            break
        chosen.append(i)
        d = np.minimum(d, np.linalg.norm(Z - Z[i], axis=1))
    return chosen


def stage_select(data: Path):
    cands = json.loads((data / "candidates.json").read_text(encoding="utf-8"))
    cands = [c for c in cands if not math.isnan(c["elev"])]
    X = np.array([env_vector(c) for c in cands])
    Z = rank_normalise(X)
    # start from the place nearest the centroid, then always go to the frontier
    start = int(np.linalg.norm(Z - Z.mean(axis=0), axis=1).argmin())
    order = maximin_order(Z, start)
    ranked = []
    for k, i in enumerate(order):
        c = dict(cands[i])
        c["maximin_rank"] = k
        ranked.append(c)
    (data / "sample_order.json").write_text(json.dumps(ranked, indent=0), encoding="utf-8")
    log(f"select: ordered {len(ranked)} candidates by maximin")



"""Write src/village/village_real_layout.gd from the measured real layouts
(tests/fixtures/settlements/layout_stats.json, made by layout_stats.py).

The generator reads the TABLE, never the fixture: the fixture is not shipped
in a release, the table is. Re-run after layout_stats.py:

    python -I tools/settlements/emit_layout_table.py --repo .

What is taken, per culture, and why:

* Only the HISTORIC sites (the curated list: old villages and phenomena), not
  the environment-sampled ones. A sampled GB/US/CA/AU site is a modern
  suburb; its 121 m2 median house is the opposite of what a medieval village
  generator wants. The historic pool's median main building is 86 m2.
* A culture with few historic sites is shrunk toward the historic pool,
  weight n / (n + PRIOR_SITES), so one odd site cannot set a culture.
* The main-building area quantiles and the per-site log spread of main
  buildings (>= 25 m2, not tagged an outbuilding), the median wall-to-wall
  gap and the share of buildings that touch a neighbour, and the pooled
  distance from a town wall to the nearest building.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
import survey as sv  # noqa: E402

PRIOR_SITES = 3.0
CULTURES = ["english", "frankish", "norse", "alpine", "moorish", "eastern", "blighted",
            "mediterranean", "east_asian", "saharan"]
# cultures with no country of their own in the survey's map borrow a neighbour
BORROW = {"blighted": "english", "eastern": "eastern"}
# survey.CC_CULTURE maps the New World to "english" for its LANGUAGE; a pueblo
# or a Canadian suburb is not an English village, so english reads only these
OWN_COUNTRIES = {"english": {"GB", "IE"}}


def med(rows, key, q):
    v = [r[key][q] for r in rows if r.get(key) and q in r[key]]
    return float(np.median(v)) if v else float("nan")


def summary(rows):
    return {
        "area_p10": med(rows, "area_main", "p10"),
        "area_p25": med(rows, "area_main", "p25"),
        "area_p50": med(rows, "area_main", "p50"),
        "area_p75": med(rows, "area_main", "p75"),
        "area_p90": med(rows, "area_main", "p90"),
        "log_sd": float(np.median([r["main_log_sd"] for r in rows if r.get("main_log_sd")])),
        "aspect_p50": med(rows, "aspect", "p50"),
        "gap_p50": med(rows, "gap_m", "p50"),
        "gap_p90": med(rows, "gap_m", "p90"),
        "touching": float(np.median([r["touching_share"] for r in rows])),
        "sites": len(rows),
    }


def shrink(own, pool, n):
    w = n / (n + PRIOR_SITES)
    out = {}
    for k, v in pool.items():
        if k == "sites":
            continue
        o = own.get(k, float("nan")) if own else float("nan")
        out[k] = round(v if (o != o) else w * o + (1.0 - w) * v, 3)
    out["sites"] = n
    return out


def build_table(repo: Path):
    """(stats, historic rows, pool, {culture: row}) -- what the generator reads,
    and what layout_compare.py judges against."""
    stats = json.loads((repo / "tests/fixtures/settlements/layout_stats.json").read_text(encoding="utf-8"))
    fx = json.loads((repo / "tests/fixtures/settlements/world_settlements.json").read_text(encoding="utf-8"))
    source = {s["id"]: s.get("source") for s in fx["sites"]}
    historic = [r for r in stats["sites"] if source.get(r["id"]) != "sampled" and r.get("area_main")]
    pool = summary(historic)
    table = {}
    for c in CULTURES:
        look = BORROW.get(c, c)
        own_rows = [r for r in historic if sv.CC_CULTURE.get(r["cc"], "") == look
                    and r["cc"] in OWN_COUNTRIES.get(look, {r["cc"]})]
        table[c] = shrink(summary(own_rows) if own_rows else None, pool, len(own_rows))
    return stats, historic, pool, table


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--repo", default=".")
    a = ap.parse_args()
    repo = Path(a.repo)
    stats, historic, pool, table = build_table(repo)
    wall = stats["pooled"].get("wall_to_building_m", {})
    lines = [
        "class_name VillageRealLayout",
        "extends RefCounted",
        "## GENERATED by tools/settlements/emit_layout_table.py from",
        "## tests/fixtures/settlements/layout_stats.json (tools/settlements/layout_stats.py",
        "## over the survey's cached OSM answers). Do not edit by hand: re-run both.",
        "##",
        "## What real old villages measure, per culture: the main buildings'",
        "## footprint quantiles (m2) and their per-site log spread, the plan aspect,",
        "## the wall-to-wall gap to the nearest neighbour (m) and the share of",
        "## buildings that touch one. Historic sites only, shrunk toward their pool",
        f"## by n / (n + {PRIOR_SITES:g}). {len(historic)} historic sites; pool median house "
        f"{pool['area_p50']:.0f} m2.",
        "## docs/VILLAGE_REAL_LAYOUT.md says how the generator uses each number.",
        "",
        "const POOL := " + _gd(dict(pool, sites=len(historic))),
        "",
        "const BY_CULTURE := {",
    ]
    for c in CULTURES:
        lines.append(f"\t&\"{c}\": {_gd(table[c])},")
    lines += [
        "}",
        "",
        "## A town wall's distance to the nearest building inside it, sampled every",
        f"## 5 m along {stats['pooled'].get('walled_sites', 0)} walled sites (median of the per-site quantiles).",
        "const WALL_TO_BUILDING_M := " + _gd({k: round(v, 2) for k, v in wall.items()}),
        "",
        "",
        "## The culture's row, or the pool's.",
        "static func of(culture: StringName) -> Dictionary:",
        "\treturn BY_CULTURE.get(culture, POOL)",
        "",
    ]
    out = repo / "src/village/village_real_layout.gd"
    out.write_bytes(("\n".join(lines)).encode("utf-8"))
    print(f"wrote {out}")
    for c in CULTURES:
        t = table[c]
        print(f"{c:14s} n={t['sites']:2d} area {t['area_p10']:.0f}/{t['area_p50']:.0f}/{t['area_p90']:.0f} "
              f"sd {t['log_sd']:.2f} gap {t['gap_p50']:.1f} touch {t['touching']:.2f}")


def _gd(d):
    parts = []
    for k, v in d.items():
        if isinstance(v, float):
            parts.append(f"\"{k}\": {v:.3f}")
        else:
            parts.append(f"\"{k}\": {v}")
    return "{" + ", ".join(parts) + "}"


if __name__ == "__main__":
    main()

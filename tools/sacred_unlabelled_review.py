"""Unlabelled evidence for the LIVE-SACRED acceptance review.

The renders from tools/render_sacred_exterior.gd are labelled by id in their
file names. This tool hides that: it shuffles the cases with a fixed seed,
renames every image to case_NN__<view>.jpg, and keeps the mapping in a key
file the reviewer does not open until the verdicts are written. It then asks
the local vision model (waterfree vision, see skill://waterfree-vision) the
same open questions for every case, without telling it the family, style,
form or cult, and stores the answers verbatim.

    python -I tools/sacred_unlabelled_review.py prepare \
        artifacts/x/renders artifacts/x/unlabelled --key=artifacts/x/key.json
    python -I tools/sacred_unlabelled_review.py review \
        artifacts/x/unlabelled artifacts/x/answers.json
    python -I tools/sacred_unlabelled_review.py map \
        artifacts/x/verdicts.json artifacts/x/key.json

`prepare` is deterministic for a given --seed. `review` never reads the key.
`map` is the only step that rejoins the two, and it is run after the verdicts
file exists.
"""

import argparse
import hashlib
import json
import os
import random
import shutil
import subprocess
import sys

VIEWS = {
    "__front.jpg": "exterior_west",
    "__side.jpg": "exterior_side",
    "__entry.jpg": "interior_entry",
    "__cutaway.jpg": "interior_cutaway",
}
CONTROL_PREFIX = "__control_"

EXTERIOR_QUESTION = (
    "These images show one building from outside, generated by a procedural "
    "architectural generator. Describe what kind of building it is and what "
    "architectural style or tradition it belongs to. Name the visible "
    "features: massing, entrance, roof, towers or domes, windows, material, "
    "ornament. Say whether it looks structurally finished: no missing walls, "
    "no floating parts, no gaps."
)
INTERIOR_QUESTION = (
    "Image 1 is a first-person view from just inside the entrance looking "
    "down the main axis of a generated building. Image 2 is the same "
    "building with its roof removed, seen from above; pieces of trim that "
    "stood on the removed roof may appear to float, ignore those. Describe, "
    "using what you can actually see: (a) is the way ahead clear of "
    "obstructions; (b) what stands at the far end, and is it visible and "
    "recognisable from the entrance; (c) where people would stand or sit, "
    "and whether that zone is arranged around the axis; (d) any broken or "
    "unfinished geometry, or floor-level objects that float."
)
CONTROL_QUESTION = (
    "This is a first-person view from just inside the entrance looking down "
    "the main axis of a generated building. Describe, using what you can "
    "actually see: (a) is the way ahead clear of obstructions; (b) what "
    "stands at the far end, and is it visible from the entrance; (c) any "
    "broken, floating or unfinished geometry."
)


def case_slug(filename):
    for suffix in VIEWS:
        if filename.endswith(suffix):
            return filename[: -len(suffix)]
    if CONTROL_PREFIX in filename:
        return filename.split(CONTROL_PREFIX)[0]
    return None


def view_name(filename):
    for suffix, name in VIEWS.items():
        if filename.endswith(suffix):
            return name
    if CONTROL_PREFIX in filename:
        return "interior_entry"
    return None


def prepare(renders, out, key_path, seed):
    groups = {}
    for filename in sorted(os.listdir(renders)):
        if not filename.endswith(".jpg"):
            continue
        slug = case_slug(filename)
        if slug is None:
            continue
        groups.setdefault(slug, []).append(filename)
    slugs = sorted(groups)
    rng = random.Random(seed)
    rng.shuffle(slugs)
    os.makedirs(out, exist_ok=True)
    key = {"seed": seed, "renders": os.path.abspath(renders),
           "cases": {}, "unlabelled_only": True}
    for index, slug in enumerate(slugs, 1):
        tag = "case_%02d" % index
        files = sorted(groups[slug], key=view_name)
        entry = {"source_slug": slug, "images": {}}
        for filename in files:
            view = view_name(filename)
            target = "%s__%s.jpg" % (tag, view)
            shutil.copyfile(os.path.join(renders, filename),
                            os.path.join(out, target))
            entry["images"][view] = target
        key["cases"][tag] = entry
        print(tag, "prepared", len(files), "images")
    with open(key_path, "w", encoding="utf-8") as handle:
        json.dump(key, handle, indent=1)
    print("key written to", key_path, "(%d cases)" % len(key["cases"]))


def vision(images, question):
    command = ["waterfree", "vision", "look"] + images + [
        "--purpose", "describe", "--model", "qwen2.5vl:7b",
        "-q", question]
    environment = dict(os.environ)
    environment.setdefault("WATERFREE_VISION_TIMEOUT", "600")
    for attempt in range(2):
        done = subprocess.run(command, capture_output=True, text=True,
                              encoding="utf-8", env=environment)
        if done.returncode == 0:
            try:
                return json.loads(done.stdout)
            except json.JSONDecodeError:
                return {"error": "unparseable vision output", "raw": done.stdout}
        if attempt == 1:
            return {"error": done.stderr.strip() or done.stdout.strip(),
                    "returncode": done.returncode}
    return {"error": "vision call did not run"}


def _has_error(case_entry):
    for key in ("exterior", "interior"):
        answer = case_entry.get(key) or {}
        if "error" in (answer.get("answer") or {}):
            return True
    return False


def review(unlabelled, answers_path):
    cases = {}
    for filename in sorted(os.listdir(unlabelled)):
        if not filename.endswith(".jpg"):
            continue
        tag = filename.split("__")[0]
        kind = filename.split("__")[1][: -len(".jpg")]
        cases.setdefault(tag, {})[kind] = os.path.join(unlabelled, filename)
    answers = {"tool": "waterfree vision look",
               "model": "qwen2.5vl:7b", "purpose": "describe",
               "cases": {}}
    if os.path.exists(answers_path):
        with open(answers_path, encoding="utf-8") as handle:
            answers["cases"] = json.load(handle).get("cases", {})
    for tag, images in cases.items():
        done_case = answers["cases"].get(tag, {})
        if done_case and not _has_error(done_case):
            print(tag, "already answered", flush=True)
            continue
        entry = {"images": images, "exterior": None, "interior": None}
        exterior = [images[k] for k in ("exterior_west", "exterior_side")
                    if k in images]
        interior = [images[k] for k in ("interior_entry", "interior_cutaway")
                    if k in images]
        if exterior:
            print(tag, "exterior ...", flush=True)
            entry["exterior"] = {"question": EXTERIOR_QUESTION,
                                 "answer": vision(exterior, EXTERIOR_QUESTION)}
        if interior:
            print(tag, "interior ...", flush=True)
            question = INTERIOR_QUESTION if len(interior) > 1 else CONTROL_QUESTION
            entry["interior"] = {"question": question,
                                 "answer": vision(interior, question)}
        answers["cases"][tag] = entry
        with open(answers_path, "w", encoding="utf-8") as handle:
            json.dump(answers, handle, indent=1)
    print("answers written to", answers_path, "(%d cases)" % len(answers["cases"]))


def digest(path):
    with open(path, "rb") as handle:
        return hashlib.sha256(handle.read()).hexdigest()


def map_verdicts(verdicts_path, key_path):
    with open(verdicts_path, encoding="utf-8") as handle:
        verdicts = json.load(handle)
    # A verdict file may be the bare tag map or carry it under "cases".
    verdicts = verdicts.get("cases", verdicts)
    with open(key_path, encoding="utf-8") as handle:
        key = json.load(handle)
    rows = []
    for tag, entry in key["cases"].items():
        verdict = verdicts.get(tag)
        rows.append({"case": tag, "id": entry["source_slug"],
                     "images": entry["images"], "verdict": verdict})
    print(json.dumps({"key_sha256": digest(key_path),
                      "verdicts_sha256": digest(verdicts_path),
                      "rows": rows}, indent=1))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    sub = parser.add_subparsers(dest="command", required=True)
    prep = sub.add_parser("prepare")
    prep.add_argument("renders")
    prep.add_argument("out")
    prep.add_argument("--key", required=True)
    prep.add_argument("--seed", type=int, default=20261023)
    rev = sub.add_parser("review")
    rev.add_argument("unlabelled")
    rev.add_argument("answers")
    mp = sub.add_parser("map")
    mp.add_argument("verdicts")
    mp.add_argument("key")
    args = parser.parse_args()
    if args.command == "prepare":
        prepare(args.renders, args.out, args.key, args.seed)
    elif args.command == "review":
        review(args.unlabelled, args.answers)
    else:
        map_verdicts(args.verdicts, args.key)


if __name__ == "__main__":
    sys.exit(main())
